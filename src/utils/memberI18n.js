export const getMemberLang = () => {
  try { return localStorage.getItem('memberLang') || 'zh'; } catch { return 'zh'; }
};

export const isEn = () => getMemberLang() === 'en';
export const isJa = () => getMemberLang() === 'ja';

// 循環切換：中文 → English → 日本語 → 中文
export const toggleMemberLang = () => {
  try {
    const cur = getMemberLang();
    const next = cur === 'zh' ? 'en' : cur === 'en' ? 'ja' : 'zh';
    localStorage.setItem('memberLang', next);
  } catch {}
  window.location.reload();
};

// 切換鈕顯示「下一個語言」的名稱（中文模式顯示 EN、英文模式顯示 日本語、日文模式顯示 中文）
export const nextLangLabel = () => {
  const cur = getMemberLang();
  return cur === 'zh' ? 'EN' : cur === 'en' ? '日本語' : '中文';
};

// 中文模式（預設）→ 原樣返回；英/日模式 → 查對應字典，查無仍原樣返回（安全 fallback）
export const t = (zh) => {
  const lang = getMemberLang();
  if (lang === 'en') return DICT_EN[zh] || zh;
  if (lang === 'ja') return DICT_JA[zh] || zh;
  return zh;
};

// 三選一組字（給帶變數/JSX 的手刻句子用，取代原本的 isEn() 三元）：tt(中文, English, 日本語)
// 未提供對應語言時，日文回退英文、英文回退中文——避免漏翻譯時整句消失。
export const tt = (zh, en, ja) => {
  const lang = getMemberLang();
  if (lang === 'ja') return ja ?? en ?? zh;
  if (lang === 'en') return en ?? zh;
  return zh;
};
